#!/usr/bin/env node
// Combines every migration + the seed into supabase/setup.sql, so a new
// Supabase project can be set up by pasting ONE file into the SQL editor.
//   npm run setup-sql

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "supabase/migrations");
const parts = readdirSync(dir)
  .filter((f) => f.endsWith(".sql"))
  .sort()
  .map((f) => `-- ════ migrations/${f} ════\n${readFileSync(join(dir, f), "utf8")}`);
parts.push(`-- ════ seed.sql ════\n${readFileSync(join(root, "supabase/seed.sql"), "utf8")}`);

const header = `-- GENERATED by \`npm run setup-sql\` — do not edit by hand.
-- One-shot setup for a NEW, EMPTY Supabase project: paste this whole file into
-- Supabase → SQL Editor → New query → Run.
-- (For an existing database, run only the migrations you haven't applied yet.)

`;
writeFileSync(join(root, "supabase/setup.sql"), header + parts.join("\n\n"));
console.log("Wrote supabase/setup.sql");
