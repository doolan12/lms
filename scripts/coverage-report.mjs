#!/usr/bin/env node
// Loads the migrations + seed into an in-memory Postgres (PGlite), then writes
// docs/curriculum-coverage.md showing how every TLILIC0003 Knowledge Evidence
// and Performance Evidence item is covered by lessons and quiz questions.
//
//   npm run coverage            → writes the report
//   npm run coverage -- --check → also exits 1 if any item has no question
//
// Supabase's auth schema and roles are stubbed so the SQL runs unchanged.

import { PGlite } from "@electric-sql/pglite";
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const db = new PGlite();

await db.exec(`
  create role anon; create role authenticated;
  create schema auth;
  create table auth.users (id uuid primary key, raw_user_meta_data jsonb default '{}');
  create function auth.uid() returns uuid language sql stable as $$ select null::uuid $$;
`);
const migrationsDir = join(root, "supabase/migrations");
for (const f of readdirSync(migrationsDir).filter((f) => f.endsWith(".sql")).sort()) {
  await db.exec(readFileSync(join(migrationsDir, f), "utf8"));
}
await db.exec(readFileSync(join(root, "supabase/seed.sql"), "utf8"));

const rows = async (sql) => (await db.query(sql)).rows;

const items = await rows(`select code, kind, description from curriculum_items order by position`);
const lessons = await rows(`
  select l.title, l.refs, m.position as module from lessons l join modules m on m.id = l.module_id
  order by m.position, l.position`);
const questions = await rows(`
  select split_part(qn.prompt, E'\n', 1) as prompt, qn.refs, qn.is_calculation,
         qz.title as quiz, qz.is_final, qn.position
  from questions qn join quizzes qz on qz.id = qn.quiz_id
  left join modules m on m.id = qz.module_id
  order by qz.is_final, m.position nulls last, qn.position`);
const [totals] = await rows(`
  select (select count(*) from modules) modules, (select count(*) from lessons) lessons,
         (select count(*) from quizzes) quizzes, (select count(*) from questions) questions`);

// Every ref used must be a defined item
const known = new Set(items.map((i) => i.code));
const unknown = [...lessons, ...questions].flatMap((r) => r.refs).filter((c) => !known.has(c));
if (unknown.length) {
  console.error("Unknown curriculum codes used:", [...new Set(unknown)]);
  process.exit(1);
}

const untagged = questions.filter((q) => q.refs.length === 0);

const lines = [];
lines.push("# Curriculum coverage — TLILIC0003 Licence to operate a forklift truck", "");
lines.push(
  "Generated by `npm run coverage` from `supabase/seed.sql`. Maps every lesson and quiz question in the " +
    "Forklift Licence Theory course to the Knowledge Evidence (KE) and Performance Evidence (PE) in the " +
    "public TLILIC0003 Assessment Requirements (training.gov.au).",
  "",
  "> The course content is original. It does not reproduce any National Assessment Instrument (NAI) " +
    "question; NAIs are confidential to accredited assessors. Performance Evidence is practical and is " +
    "assessed on a real forklift — the course covers the knowledge that underpins each PE item.",
  "",
);
lines.push(
  `**Course:** ${totals.modules} modules · ${totals.lessons} lessons · ${totals.quizzes} quizzes · ${totals.questions} questions`,
  "",
);

const summary = (kind) => {
  lines.push("| Code | Requirement | Lessons | Questions |", "|---|---|---:|---:|");
  for (const i of items.filter((i) => i.kind === kind)) {
    const l = lessons.filter((x) => x.refs.includes(i.code)).length;
    const q = questions.filter((x) => x.refs.includes(i.code)).length;
    const flag = q === 0 ? " ⚠️" : "";
    lines.push(`| ${i.code} | ${i.description} | ${l} | ${q}${flag} |`);
  }
  lines.push("");
};

lines.push("## Knowledge Evidence", "");
summary("knowledge");
lines.push("## Performance Evidence (underpinning knowledge)", "");
summary("performance");

// Calculation questions
const MIN_CALC_TOTAL = 15;
const MIN_CALC_FINAL = 5;
const calc = questions.filter((q) => q.is_calculation);
const calcFinal = calc.filter((q) => q.is_final);
const quizTitles = [...new Set(questions.map((q) => q.quiz))];
lines.push("## Calculation questions", "");
lines.push(
  `${calc.length} calculation questions (minimum ${MIN_CALC_TOTAL}), ${calcFinal.length} in the final exam ` +
    `(minimum ${MIN_CALC_FINAL}). They cover total load weight from cartons, layers and multiple items, ` +
    "tonnes to kilograms, weighbridge dockets, the most cartons you can load, load centre (including a gap " +
    "from the backrest), and reading a load chart by load centre and lift height.",
  "",
  "| Quiz | Calculation questions | Total questions |",
  "|---|---:|---:|",
);
for (const t of quizTitles) {
  const all = questions.filter((q) => q.quiz === t);
  lines.push(`| ${t} | ${all.filter((q) => q.is_calculation).length} | ${all.length} |`);
}
lines.push("", "**All calculation questions:**", "");
for (const q of calc) lines.push(`- _${q.quiz} Q${q.position}:_ ${q.prompt}`);
lines.push("");

lines.push("## Detail by requirement", "");
for (const i of items) {
  lines.push(`### ${i.code} — ${i.description}`, "");
  const ls = lessons.filter((x) => x.refs.includes(i.code));
  const qs = questions.filter((x) => x.refs.includes(i.code));
  lines.push("**Lessons:** " + (ls.length ? ls.map((l) => `M${l.module} ${l.title}`).join("; ") : "_none_"), "");
  if (qs.length) {
    lines.push("**Questions:**", "");
    for (const q of qs) lines.push(`- _${q.quiz} Q${q.position}:_ ${q.prompt}`);
  } else {
    lines.push("**Questions:** _none_");
  }
  lines.push("");
}

mkdirSync(join(root, "docs"), { recursive: true });
const out = join(root, "docs/curriculum-coverage.md");
writeFileSync(out, lines.join("\n"));

const gaps = items.filter((i) => !questions.some((q) => q.refs.includes(i.code)));
console.log(`Wrote ${out}`);
console.log(`${totals.lessons} lessons, ${totals.questions} questions, ${items.length} requirements`);
console.log(gaps.length ? `UNCOVERED: ${gaps.map((g) => g.code).join(", ")}` : "Every requirement has at least one question.");
if (untagged.length) console.log(`Untagged questions: ${untagged.length}`);
const calcShort = calc.length < MIN_CALC_TOTAL || calcFinal.length < MIN_CALC_FINAL;
console.log(
  `Calculation questions: ${calc.length} total (min ${MIN_CALC_TOTAL}), ${calcFinal.length} in final (min ${MIN_CALC_FINAL})` +
    (calcShort ? " — TOO FEW" : ""),
);

if (process.argv.includes("--check") && (gaps.length || untagged.length || calcShort)) process.exit(1);
